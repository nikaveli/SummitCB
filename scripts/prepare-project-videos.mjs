import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { projectVideoGroups } from '../src/project-video-catalog.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const inputDirectory=path.join(root,'Project-page-videos');
const outputDirectory=path.join(root,'public/assets/project-films');
const ffmpeg=process.env.FFMPEG||'ffmpeg';
const ffprobe=process.env.FFPROBE||'ffprobe';
const cwebp=process.env.CWEBP||'cwebp';
await rm(outputDirectory,{recursive:true,force:true});
await mkdir(outputDirectory,{recursive:true});

const assets={},report=[];
for(const group of projectVideoGroups)for(const clip of group.clips) {
  const input=path.join(inputDirectory,clip.source);
  const originalBytes=(await stat(input)).size;
  const versions={};
  for(const height of [480,720]) {
    const temp=path.join(outputDirectory,`${clip.id}-${height}.tmp.mp4`);
    execFileSync(ffmpeg,['-hide_banner','-loglevel','error','-i',input,'-map','0:v:0','-an','-sn','-dn','-vf',`scale=-2:${height}:flags=lanczos`,'-c:v','libx264','-preset','slow','-crf',height===480?'26':'25','-maxrate',height===480?'800k':'1400k','-bufsize',height===480?'1600k':'2800k','-pix_fmt','yuv420p','-profile:v','high','-level','3.1','-g','48','-threads','3','-map_metadata','-1','-movflags','+faststart','-y',temp],{stdio:['ignore','ignore','inherit']});
    const data=await readFile(temp),hash=createHash('sha256').update(data).digest('hex').slice(0,12);
    const file=`${clip.id}-${height}-${hash}.mp4`;
    await rename(temp,path.join(outputDirectory,file));
    const media=JSON.parse(execFileSync(ffprobe,['-v','quiet','-show_streams','-show_format','-print_format','json',path.join(outputDirectory,file)],{encoding:'utf8'}));
    const video=media.streams.find(stream=>stream.codec_type==='video');
    versions[height]={url:'/assets/project-films/'+file,bytes:data.length,width:video.width,height:video.height,duration:Number(media.format.duration)};
  }
  const posterPng=path.join(outputDirectory,`${clip.id}-poster.tmp.png`);
  const posterTemp=path.join(outputDirectory,`${clip.id}-poster.tmp.webp`);
  execFileSync(ffmpeg,['-hide_banner','-loglevel','error','-ss',String(clip.posterTime||1),'-i',input,'-frames:v','1','-vf','scale=1280:720:force_original_aspect_ratio=increase,crop=1280:720','-map_metadata','-1','-y',posterPng],{stdio:['ignore','ignore','inherit']});
  execFileSync(cwebp,['-quiet','-q','84','-m','6',posterPng,'-o',posterTemp],{stdio:['ignore','ignore','inherit']});
  await rm(posterPng);
  const posterData=await readFile(posterTemp),posterHash=createHash('sha256').update(posterData).digest('hex').slice(0,12);
  const posterFile=`${clip.id}-poster-${posterHash}.webp`;
  await rename(posterTemp,path.join(outputDirectory,posterFile));
  versions.poster={url:'/assets/project-films/'+posterFile,bytes:posterData.length,width:1280,height:720};
  assets[clip.id]=versions;
  report.push({id:clip.id,source:'Project-page-videos/'+clip.source,originalBytes,versions});
  console.log(`${clip.id}: 480p ${Math.round(versions[480].bytes/1024)} KB; 720p ${Math.round(versions[720].bytes/1024)} KB; poster ${Math.round(versions.poster.bytes/1024)} KB`);
}
await writeFile(path.join(root,'src/project-video-assets.mjs'),'// Generated by scripts/prepare-project-videos.mjs.\nexport const projectVideoAssets = '+JSON.stringify(assets,null,2)+';\n');
await writeFile(path.join(root,'data/project-video-assets.json'),JSON.stringify(report,null,2)+'\n');
console.log(`${report.length} project films prepared. Original footage remains unchanged.`);
